/**
 * Minimal PikPak drive client: login, token refresh, and recursive file listing.
 *
 * Stream links are still generated by StremThru. The client only needs PikPak file IDs
 * so the extension can build the same `stremthru://store/pikpak/...` links itself.
 */
internal class PikPakClient(
    private val client: OkHttpClient,
    private val username: String,
    private val password: String,
    private val tokenStore: TokenStore = NoOpTokenStore,
    refreshSeed: String? = null,
) {
    interface TokenStore {
        fun load(): StoredTokens?
        fun save(tokens: StoredTokens)

        /** Drops a refresh token pasted from the web session after PikPak rejects it. */
        fun clearRefreshSeed() = Unit
    }

    data class StoredTokens(
        val accessToken: String,
        val refreshToken: String,
        val userId: String,
        val expiresAt: Long,
    )

    private object NoOpTokenStore : TokenStore {
        override fun load(): StoredTokens? = null
        override fun save(tokens: StoredTokens) = Unit
    }
    data class Listing(
        val name: String,
        val rootId: String,
        val files: List<FileEntry>,
    )

    data class FileEntry(
        val id: String,
        val name: String,
        val path: String,
        val kind: String,
        val size: String? = null,
        val createdTime: String? = null,
        val thumbnailLink: String? = null,
    )

    private val json = Json {
        ignoreUnknownKeys = true
        explicitNulls = false
        // Fields such as grant_type have defaults; the API requires them in the body.
        encodeDefaults = true
    }

    private val deviceId = getDeviceId("$username:$password")
    private val mutex = Mutex()

    private var accessToken: String? = null
    private var refreshToken: String? = null
    private var userId: String? = null
    private var expiresAt: Long = 0

    private var driveCaptcha: String? = null
    private var driveCaptchaExpiresAt: Long = 0

    private val hasRefreshSeed = !refreshSeed.isNullOrBlank()
    private var refreshSource: String = "none"

    init {
        val stored = tokenStore.load()
        if (stored != null) {
            accessToken = stored.accessToken
            refreshToken = stored.refreshToken
            userId = stored.userId
            expiresAt = stored.expiresAt
            refreshSource = "stored"
        } else {
            // A refresh token pasted from the web session avoids the login captcha entirely.
            refreshToken = refreshSeed?.takeIf { it.isNotBlank() }
            refreshSource = if (refreshToken != null) "seed" else "none"
        }
    }

    private fun persistTokens() {
        val access = accessToken ?: return
        val refresh = refreshToken ?: return
        runCatching {
            tokenStore.save(StoredTokens(access, refresh, userId.orEmpty(), expiresAt))
        }
    }

    suspend fun listMyPack(): List<PikPakFile> = mutex.withLock {
        ensureAuthLocked()

        val rootFiles = listChildrenLocked("")
        val myPack = rootFiles.firstOrNull {
            it.kind == KIND_FOLDER && it.name.equals("My Pack", ignoreCase = true)
        } ?: throw IOException("PikPak 'My Pack' folder not found")

        listChildrenLocked(myPack.id)
            .filter { it.id.isNotBlank() && it.trashed != true }
            .filter { it.phase == null || it.phase == PHASE_COMPLETE }
    }

    suspend fun list(itemId: String): Listing = mutex.withLock {
        ensureAuthLocked()
        val root = getFileLocked(itemId)

        val files = mutableListOf<FileEntry>()
        if (root.kind == KIND_FOLDER) {
            listRecursiveLocked(root.id, "", files, 0)
        } else {
            files.add(
                FileEntry(
                    id = root.id,
                    name = root.name,
                    path = "/${root.name}",
                    kind = root.kind,
                    size = root.size,
                    createdTime = root.createdTime,
                    thumbnailLink = root.thumbnailLink,
                ),
            )
        }

        Listing(root.name, root.id, files)
    }

    suspend fun listChildren(folderId: String): List<PikPakFile> = mutex.withLock {
        ensureAuthLocked()
        listChildrenLocked(folderId)
            .filter { it.id.isNotBlank() && it.trashed != true }
            .filter { it.phase == null || it.phase == PHASE_COMPLETE }
    }

    suspend fun getStreamUrl(fileId: String): String? = mutex.withLock {
        ensureAuthLocked()
        val file = getFileLocked(fileId)

        val media = file.medias.orEmpty()
            .filter { it.link?.url?.isNotBlank() == true }
            .maxWithOrNull(
                compareBy<PikPakMedia> { it.isDefault }
                    .thenBy { it.isOrigin },
            )

        media?.link?.url?.takeIf { it.isNotBlank() }
            ?: file.webContentLink?.takeIf { it.isNotBlank() }
    }

    /**
     * Resolves a folder ID or a path such as `My Shared/Anime` to a folder.
     * Paths are matched by name, starting at the drive root (so `My Pack/...`
     * works) or at My Pack when the first segment is not a root folder.
     */
    suspend fun resolveFolder(input: String): PikPakFile? = mutex.withLock {
        ensureAuthLocked()

        val cleaned = input.trim().trim('/')
        if (cleaned.isBlank()) return null

        if (ID_HINT_REGEX.matches(cleaned)) {
            runCatching { getFileLocked(cleaned) }
                .getOrNull()
                ?.takeIf { it.kind == KIND_FOLDER && it.id.isNotBlank() }
                ?.let { return it }
        }

        val segments = cleaned.split('/').map { it.trim() }.filter { it.isNotBlank() }
        if (segments.isEmpty()) return null

        val rootFolders = listChildrenLocked("")
            .filter { it.kind == KIND_FOLDER && it.id.isNotBlank() }

        var folder = rootFolders.firstOrNull { it.name.equals(segments.first(), ignoreCase = true) }
        var remaining = segments
        if (folder != null) {
            remaining = segments.drop(1)
        } else {
            folder = rootFolders.firstOrNull { it.name.equals("My Pack", ignoreCase = true) } ?: return null
        }

        for (segment in remaining) {
            val parentId = folder?.id ?: return null
            folder = listChildrenLocked(parentId).firstOrNull {
                it.kind == KIND_FOLDER && it.name.equals(segment, ignoreCase = true)
            } ?: return null
        }

        return folder
    }

    private suspend fun listChildrenLocked(parentId: String): List<PikPakFile> {
        val result = mutableListOf<PikPakFile>()
        var pageToken = ""
        var pageCount = 0
        do {
            if (++pageCount > MAX_PAGES) break
            val data = listFilesLocked(parentId, pageToken)
            data.error?.let { throw IOException("PikPak list error: $it ${data.errorDescription.orEmpty()}") }
            result.addAll(data.files.orEmpty())
            pageToken = data.nextPageToken.orEmpty()
        } while (pageToken.isNotEmpty())
        return result
    }

    private suspend fun listRecursiveLocked(
        folderId: String,
        parentPath: String,
        result: MutableList<FileEntry>,
        depth: Int,
    ) {
        if (depth > MAX_DEPTH) return

        var pageToken = ""
        var pageCount = 0
        do {
            if (++pageCount > MAX_PAGES) break
            val data = listFilesLocked(folderId, pageToken)
            data.error?.let { throw IOException("PikPak list error: $it ${data.errorDescription.orEmpty()}") }

            for (file in data.files.orEmpty()) {
                if (file.id.isBlank()) continue
                if (file.trashed == true) continue
                if (file.phase != null && file.phase != PHASE_COMPLETE) continue

                val path = if (parentPath.isEmpty()) "/${file.name}" else "$parentPath/${file.name}"
                if (file.kind == KIND_FOLDER) {
                    listRecursiveLocked(file.id, path, result, depth + 1)
                } else {
                    result.add(
                        FileEntry(
                            id = file.id,
                            name = file.name,
                            path = path,
                            kind = file.kind,
                            size = file.size,
                            createdTime = file.createdTime,
                            thumbnailLink = file.thumbnailLink,
                        ),
                    )
                }
            }

            pageToken = data.nextPageToken.orEmpty()
        } while (pageToken.isNotEmpty())
    }

    private suspend fun getFileLocked(fileId: String): PikPakFile {
        val url = DRIVE_BASE.newBuilder()
            .addPathSegment("drive")
            .addPathSegment("v1")
            .addPathSegment("files")
            .addPathSegment(fileId)
            .build()

        driveGet(url).use { response ->
            val body = response.body.string()
            if (!response.isSuccessful) {
                throw IOException("PikPak get file HTTP ${response.code}: $body")
            }
            val file = json.decodeFromString<PikPakFile>(body)
            if (file.id.isBlank()) {
                throw IOException("PikPak get file failed: ${file.error.orEmpty()} ${file.errorDescription.orEmpty()}")
            }
            return file
        }
    }

    private suspend fun listFilesLocked(parentId: String, pageToken: String): PikPakFileListResponse {
        val url = DRIVE_BASE.newBuilder()
            .addPathSegment("drive")
            .addPathSegment("v1")
            .addPathSegment("files")
            .addQueryParameter("thumbnail_size", "SIZE_MEDIUM")
            .addQueryParameter("limit", "500")
            .addQueryParameter("filters", FILTERS_JSON)
            .apply {
                if (parentId.isNotBlank()) addQueryParameter("parent_id", parentId)
                if (pageToken.isNotBlank()) addQueryParameter("page_token", pageToken)
            }
            .build()

        driveGet(url).use { response ->
            val body = response.body.string()
            if (!response.isSuccessful) {
                throw IOException("PikPak list files HTTP ${response.code}: $body")
            }
            return json.decodeFromString<PikPakFileListResponse>(body)
        }
    }

    private suspend fun driveGet(url: HttpUrl): okhttp3.Response {
        val action = "GET:${url.encodedPath}"
        ensureDriveCaptchaLocked(action)
        var response = client.get(
            url,
            driveHeaders(),
            CacheControl.FORCE_NETWORK,
            ensureSuccess = false,
        )

        if (response.code == 401 || response.code == 403) {
            response.close()
            ensureAuthLocked(forceRefresh = true)
            driveCaptcha = null
            driveCaptchaExpiresAt = 0
            ensureDriveCaptchaLocked(action)
            response = client.get(
                url,
                driveHeaders(),
                CacheControl.FORCE_NETWORK,
                ensureSuccess = false,
            )
        }
        return response
    }

    private suspend fun ensureAuthLocked(forceRefresh: Boolean = false) {
        val now = nowSeconds()
        if (!forceRefresh && accessToken != null && now < expiresAt - 600) return

        if (refreshLocked()) return

        if (hasRefreshSeed && isRefreshTokenRejected()) {
            // PikPak rotates refresh tokens, so a pasted one is often already dead.
            // Do not let it block the account login that can still work.
            Log.d(AUTH_TAG, "refresh seed rejected, falling back to account login: $lastRefreshError")
            tokenStore.clearRefreshSeed()
            refreshToken = null
            expiresAt = 0
            try {
                signInLocked()
                return
            } catch (e: IOException) {
                val savedError = lastRefreshError?.let { " Saved token error: $it." }.orEmpty()
                throw IOException(
                    "PikPak rejected the saved refresh token and the account sign-in failed too: " +
                        "${e.message}.$savedError Copy a fresh refresh token from mypikpak.com, " +
                        "or wait for PikPak's login rate limit to expire.",
                    e,
                )
            }
        }

        if (hasRefreshSeed) {
            throw IOException("Could not refresh the PikPak session: $lastRefreshError")
        }

        signInLocked()
    }

    private fun isRefreshTokenRejected(): Boolean {
        val error = lastRefreshError ?: return false
        return error.contains("invalid_grant", ignoreCase = true) || error.contains("4126")
    }

    private suspend fun ensureDriveCaptchaLocked(action: String) {
        val now = nowSeconds()
        if (driveCaptcha != null && now < driveCaptchaExpiresAt - 30) return

        val captcha = initCaptchaLocked(
            action = action,
            loginIdentifier = null,
            userId = userId,
        )
        driveCaptcha = captcha.captchaToken
        driveCaptchaExpiresAt = now + captcha.expiresIn
    }

    private suspend fun signInLocked() {
        var lastError: Exception? = null
        for (attempt in 1..MAX_SIGNIN_ATTEMPTS) {
            if (attempt > 1) delay(SIGNIN_RETRY_DELAY_MS * attempt)
            try {
                signInOnceLocked()
                Log.d(AUTH_TAG, "sign in ok attempt=$attempt")
                return
            } catch (e: IOException) {
                val message = e.message.orEmpty()
                val retryable = message.contains("captcha", ignoreCase = true) &&
                    !message.contains("too frequent", ignoreCase = true)
                Log.d(AUTH_TAG, "sign in failed attempt=$attempt retryable=$retryable error=$message")
                if (!retryable) throw e
                lastError = e
            }
        }

        throw IOException(
            "PikPak rejected the sign-in captcha $MAX_SIGNIN_ATTEMPTS times. " +
                "Wait a minute and try again, then check the account in the extension settings.",
            lastError,
        )
    }

    private suspend fun signInOnceLocked() {
        val captcha = initCaptchaLocked(
            action = LOGIN_CAPTCHA_ACTION,
            loginIdentifier = username,
            userId = null,
        )

        val form = json.encodeToString(PikPakSignInRequest(username, password, CLIENT_ID))
            .toRequestBody(JSON_MEDIA_TYPE)

        val url = USER_BASE.newBuilder()
            .addPathSegment("v1")
            .addPathSegment("auth")
            .addPathSegment("signin")
            .build()

        client.post(
            url,
            clientHeaders(captchaToken = captcha.captchaToken),
            form,
            ensureSuccess = false,
        ).use { response ->
            val body = response.body.string()
            if (!response.isSuccessful) {
                val failure = runCatching { json.decodeFromString<PikPakAuthResponse>(body) }.getOrNull()
                val reason = failure?.errorDescription
                    ?.takeIf { it.isNotBlank() }
                    ?: failure?.error?.takeIf { it.isNotBlank() }
                    ?: body
                throw IOException("PikPak sign in HTTP ${response.code}: $reason")
            }

            val data = json.decodeFromString<PikPakAuthResponse>(body)
            if (data.accessToken.isBlank()) {
                throw IOException("PikPak sign in failed: ${data.error.orEmpty()} ${data.errorDescription.orEmpty()}")
            }

            accessToken = data.accessToken
            refreshToken = data.refreshToken
            userId = data.sub.ifBlank { data.userId }
            expiresAt = nowSeconds() + data.expiresIn
            driveCaptcha = null
            driveCaptchaExpiresAt = 0
            persistTokens()
        }
    }

    private var lastRefreshError: String? = null

    private suspend fun refreshLocked(): Boolean {
        val token = refreshToken ?: return false

        val body = json.encodeToString(PikPakRefreshRequest(token, CLIENT_ID))
            .toRequestBody(JSON_MEDIA_TYPE)

        val url = USER_BASE.newBuilder()
            .addPathSegment("v1")
            .addPathSegment("auth")
            .addPathSegment("token")
            .build()

        client.post(url, clientHeaders(includeAuth = accessToken != null), body, ensureSuccess = false)
            .use { response ->
                val text = response.body.string()
                Log.d(AUTH_TAG, "refresh attempt source=$refreshSource tokenLen=${token.length} code=${response.code}")
                if (!response.isSuccessful) {
                    lastRefreshError = "HTTP ${response.code}: ${text.take(300)}"
                    Log.d(AUTH_TAG, "refresh failed tokenLen=${token.length} $lastRefreshError")
                    return false
                }

                val data = runCatching { json.decodeFromString<PikPakAuthResponse>(text) }.getOrNull()
                if (data == null || data.accessToken.isBlank()) {
                    lastRefreshError = "unreadable token response: ${text.take(300)}"
                    Log.d(AUTH_TAG, "refresh failed tokenLen=${token.length} $lastRefreshError")
                    return false
                }

                accessToken = data.accessToken
                refreshToken = data.refreshToken.ifBlank { token }
                val newUserId = data.sub.ifBlank { data.userId }
                if (newUserId.isNotBlank() && newUserId != userId) {
                    userId = newUserId
                    driveCaptcha = null
                    driveCaptchaExpiresAt = 0
                }
                expiresAt = nowSeconds() + data.expiresIn
                lastRefreshError = null
                refreshSource = "rotated"
                persistTokens()
                Log.d(AUTH_TAG, "refresh ok tokenLen=${token.length} newTokenLen=${refreshToken.orEmpty().length}")
                return true
            }
    }

    private suspend fun initCaptchaLocked(
        action: String,
        loginIdentifier: String?,
        userId: String?,
    ): PikPakCaptchaResponse {
        val isEmail = loginIdentifier?.contains('@') == true
        val isPhone = loginIdentifier != null && !isEmail && PHONE_REGEX.matches(loginIdentifier)

        val meta = if (action == LOGIN_CAPTCHA_ACTION) {
            // The web login client only sends the identifier for the sign-in action.
            PikPakCaptchaMeta(
                username = loginIdentifier?.takeIf { !isEmail && !isPhone },
                email = loginIdentifier?.takeIf { isEmail },
                phoneNumber = loginIdentifier?.takeIf { isPhone },
            )
        } else {
            val timestamp = System.currentTimeMillis().toString()
            PikPakCaptchaMeta(
                captchaSign = calculateCaptchaSign(deviceId, timestamp),
                clientVersion = CLIENT_VERSION,
                packageName = PACKAGE_NAME,
                timestamp = timestamp,
                userId = userId,
            )
        }

        val requestBody = json.encodeToString(PikPakCaptchaRequest(action, CLIENT_ID, deviceId, meta))
            .toRequestBody(JSON_MEDIA_TYPE)

        val url = USER_BASE.newBuilder()
            .addPathSegment("v1")
            .addPathSegment("shield")
            .addPathSegment("captcha")
            .addPathSegment("init")
            .build()

        client.post(
            url,
            clientHeaders(includeAuth = accessToken != null),
            requestBody,
            ensureSuccess = false,
        ).use { response ->
            val body = response.body.string()
            if (!response.isSuccessful) {
                if (response.code == 409 || body.contains("too frequent", ignoreCase = true)) {
                    throw IOException(
                        "PikPak is rate-limiting logins (\"Your operation is too frequent\"). " +
                            "Wait a while, or paste a refresh token from the web version in the extension settings.",
                    )
                }
                throw IOException("PikPak captcha HTTP ${response.code}: $body")
            }

            val data = json.decodeFromString<PikPakCaptchaResponse>(body)
            if (data.captchaToken.isBlank()) {
                throw IOException(
                    "PikPak captcha failed: ${data.error.orEmpty()} " +
                        "${data.errorDescription.orEmpty()} ${data.url.orEmpty()}",
                )
            }
            return data
        }
    }

    private fun driveHeaders(): Headers {
        val token = accessToken ?: throw IOException("PikPak is not authenticated")
        val captcha = driveCaptcha ?: throw IOException("PikPak captcha is missing")

        return Headers.Builder()
            .add("Authorization", "Bearer $token")
            .add("X-Client-Id", CLIENT_ID)
            .add("X-Client-Version", CLIENT_VERSION)
            .add("X-Device-Id", deviceId)
            .add("X-Captcha-Token", captcha)
            .add("Referer", REFERER)
            .add("User-Agent", BROWSER_UA)
            .build()
    }

    private fun clientHeaders(includeAuth: Boolean = false, captchaToken: String? = null): Headers {
        val builder = Headers.Builder()
            .add("X-Client-Id", CLIENT_ID)
            .add("X-Client-Version", CLIENT_VERSION)
            .add("X-Device-Id", deviceId)
            .add("Referer", REFERER)
            .add("User-Agent", BROWSER_UA)

        captchaToken?.takeIf { it.isNotBlank() }?.let { builder.add("X-Captcha-Token", it) }
        if (includeAuth) {
            accessToken?.let { builder.add("Authorization", "Bearer $it") }
        }
        return builder.build()
    }

    companion object {
        // Identity of PikPak's web client, the same one a browser uses at mypikpak.com.
        private const val CLIENT_ID = "YUMx5nI8ZU8Ap8pm"
        private const val CLIENT_VERSION = "2.0.0"
        private const val PACKAGE_NAME = "mypikpak.com"
        private const val REFERER = "https://mypikpak.com/"
        private const val AUTH_TAG = "PikPakAuth"
        private const val MAX_SIGNIN_ATTEMPTS = 3
        private const val SIGNIN_RETRY_DELAY_MS = 3_000L

        private const val KIND_FOLDER = "drive#folder"
        private const val PHASE_COMPLETE = "PHASE_TYPE_COMPLETE"
        private const val LOGIN_CAPTCHA_ACTION = "POST:/v1/auth/signin"
        private const val MAX_DEPTH = 10
        private const val MAX_PAGES = 200

        private const val BROWSER_UA =
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64; rv:129.0) Gecko/20100101 Firefox/129.0"

        private const val FILTERS_JSON =
            """{"trashed":{"eq":false},"phase":{"eq":"PHASE_TYPE_COMPLETE"}}"""

        private val JSON_MEDIA_TYPE = "application/json".toMediaType()
        private val ID_HINT_REGEX = Regex("^[A-Za-z0-9_-]{16,}$")
        private val USER_BASE = "https://user.mypikpak.com".toHttpUrl()
        private val DRIVE_BASE = "https://api-drive.mypikpak.com".toHttpUrl()
        private val PHONE_REGEX = Regex("\\d{11,18}")

        private val MD5_SALTS = listOf(
            "C9qPpZLN8ucRTaTiUMWYS9cQvWOE",
            "+r6CQVxjzJV6LCV",
            "F",
            "pFJRC",
            "9WXYIDGrwTCz2OiVlgZa90qpECPD6olt",
            "/750aCr4lm/Sly/c",
            "RB+DT/gZCrbV",
            "",
            "CyLsf7hdkIRxRm215hl",
            "7xHvLi2tOYP0Y92b",
            "ZGTXXxu8E/MIWaEDB+Sm/",
            "1UI3",
            "E7fP5Pfijd+7K+t6Tg/NhuLq0eEUVChpJSkrKxpO",
            "ihtqpG6FMt65+Xk+tWUH2",
            "NhXXU9rg4XXdzo7u5o",
        )

        private fun nowSeconds(): Long = System.currentTimeMillis() / 1000

        private fun getDeviceId(credential: String): String {
            val hash = MessageDigest.getInstance("SHA-256")
                .digest(credential.toByteArray(Charsets.UTF_8))
            val uuid = hash.copyOf(16)
            uuid[6] = ((uuid[6].toInt() and 0x0f) or 0x40).toByte()
            uuid[8] = ((uuid[8].toInt() and 0x3f) or 0x80).toByte()
            return uuid.toHex()
        }

        private fun calculateCaptchaSign(deviceId: String, timestamp: String): String {
            var sign = CLIENT_ID + CLIENT_VERSION + PACKAGE_NAME + deviceId + timestamp
            for (salt in MD5_SALTS) {
                sign = md5(sign + salt)
            }
            return "1.$sign"
        }

        private fun md5(value: String): String = MessageDigest.getInstance("MD5").digest(value.toByteArray(Charsets.UTF_8)).toHex()

        private fun ByteArray.toHex(): String = joinToString("") { (it.toInt() and 0xff).toString(16).padStart(2, '0') }
    }
}
