        private fun nowSeconds(): Long = System.currentTimeMillis() / 1000

        private fun getDeviceId(credential: String): String {
            val hash = MessageDigest.getInstance("SHA-256")
                .digest(credential.toByteArray(Charsets.UTF_8))
            val uuid = hash.copyOf(16)
            uuid[6] = ((uuid[6].toInt() and 0x0f) or 0x40).toByte()
            uuid[8] = ((uuid[8].toInt() and 0x3f) or 0x80).toByte()
            return uuid.toHex()
        }

        private fun calculateCaptchaSign(deviceId: String, timestamp: String): String {
            var sign = CLIENT_ID + CLIENT_VERSION + PACKAGE_NAME + deviceId + timestamp
            for (salt in MD5_SALTS) {
                sign = md5(sign + salt)
            }
            return "1.$sign"
        }

        private fun buildUserAgent(deviceId: String, userId: String): String {
            val deviceSign = "div101.$deviceId" + md5(sha1(deviceId + PACKAGE_NAME + "1appkey"))
            return listOf(
                "ANDROID-$PACKAGE_NAME/$CLIENT_VERSION",
                "protocolVersion/200",
                "accesstype/",
                "clientid/$CLIENT_ID",
                "clientversion/$CLIENT_VERSION",
                "action_type/",
                "networktype/WIFI",
                "sessionid/",
                "deviceid/$deviceId",
                "providername/NONE",
                "devicesign/$deviceSign",
                "refresh_token/",
                "sdkversion/$SDK_VERSION",
                "datetime/${System.currentTimeMillis()}",
                "usrno/$userId",
                "appname/$PACKAGE_NAME",
                "session_origin/",
                "grant_type/",
                "appid/",
                "clientip/",
                "devicename/Xiaomi_M2004j7ac",
                "osversion/13",
                "platformversion/10",
                "accessmode/",
                "devicemodel/M2004J7AC",
            ).joinToString(" ")
        }

        private fun md5(value: String): String = MessageDigest.getInstance("MD5").digest(value.toByteArray(Charsets.UTF_8)).toHex()

        private fun sha1(value: String): String = MessageDigest.getInstance("SHA-1").digest(value.toByteArray(Charsets.UTF_8)).toHex()

        private fun ByteArray.toHex(): String = joinToString("") { (it.toInt() and 0xff).toString(16).padStart(2, '0') }
    }
